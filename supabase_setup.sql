-- 3. 실시간(Realtime) 활성화
-- ---------------------------------------------------------------------------

do $$
declare
  t text;
begin
  foreach t in array array['transactions','user_settings','categories','budgets','goals','accounts','recurring','settlements','app_settings']
  loop
    begin
      execute format('alter publication supabase_realtime add table public.%I', t);
    exception when duplicate_object then
      null; -- 이미 추가되어 있으면 통과
    end;
  end loop;
end $$;

