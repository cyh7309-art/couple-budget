alter table public.accounts add column if not exists "paymentAccountId"   text;
alter table public.accounts add column if not exists "autoSettle"         boolean default false;

-- 반복 거래 금액 유형 (fixed = 자동 생성 / variable = 확인 후 입력)
alter table public.recurring add column if not exists "amountMode" text default 'fixed';
alter table public.recurring add column if not exists skips        text[] default '{}';

-- 거래 테이블에 계좌 / 반복거래 연결 컬럼 추가 (기존 테이블에도 안전하게 적용됩니다)
alter table public.transactions add column if not exists "accountId"     text;
alter table public.transactions add column if not exists "fromAccountId" text;
alter table public.transactions add column if not exists "toAccountId"   text;
alter table public.transactions add column if not exists "recurringId"   text;
alter table public.transactions add column if not exists "autoGenerated" boolean default false;
alter table public.transactions add column if not exists "cardBillingMonth" text;

-- 할부 (하나의 구매가 회차 수만큼의 거래로 나뉘어 저장됩니다)
alter table public.transactions add column if not exists "installmentId"        text;
alter table public.transactions add column if not exists "installmentSeq"       integer;
alter table public.transactions add column if not exists "installmentMonths"    integer;
alter table public.transactions add column if not exists "installmentPrincipal" bigint;
alter table public.transactions add column if not exists "installmentFee"       bigint default 0;
alter table public.transactions add column if not exists "installmentRate"      numeric default 0;

create index if not exists transactions_installment_idx on public.transactions ("installmentId");

-- ---------------------------------------------------------------------------
-- 2. 보안 (RLS) — 이 단계가 가장 중요합니다
--
--    anon key 는 브라우저 소스에 그대로 노출됩니다. RLS 가 꺼져 있으면
--    그 키를 본 누구나 가계부 전체를 읽고 지울 수 있습니다.
--    아래 정책은 "로그인한 사용자만" 접근을 허용합니다.
-- ---------------------------------------------------------------------------

alter table public.transactions  enable row level security;
alter table public.user_settings enable row level security;
alter table public.categories    enable row level security;
alter table public.budgets       enable row level security;
alter table public.goals         enable row level security;
alter table public.accounts      enable row level security;
alter table public.recurring     enable row level security;
alter table public.settlements   enable row level security;
alter table public.app_settings  enable row level security;

do $$
declare
  t text;
begin
  foreach t in array array['transactions','user_settings','categories','budgets','goals','accounts','recurring','settlements','app_settings']
  loop
    execute format('drop policy if exists "authenticated_all" on public.%I', t);
    execute format($f$
      create policy "authenticated_all" on public.%I
        for all
        to authenticated
        using (true)
        with check (true)
    $f$, t);
  end loop;
end $$;

