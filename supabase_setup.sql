-- ---------------------------------------------------------------------------
-- 1. 테이블
-- ---------------------------------------------------------------------------

create table if not exists public.transactions (
  id              text primary key,
  date            date not null,
  type            text not null check (type in ('income', 'expense', 'transfer')),
  amount          bigint not null default 0,
  "userId"        text,
  "categoryId"    text,
  "sharedType"    text,
  "paymentMethod" text,
  "isFixed"       boolean default false,
  memo            text,
  "createdAt"     timestamptz default now(),
  "updatedAt"     timestamptz default now()
);

create index if not exists transactions_date_idx on public.transactions (date desc);

create table if not exists public.user_settings (
  id     text primary key,
  name   text,
  role   text,
  avatar text
);

create table if not exists public.categories (
  id    text primary key,
  type  text not null,
  name  text not null,
  icon  text,
  color text
);

create table if not exists public.budgets (
  id           text primary key,
  month        text not null,
  "categoryId" text not null,
  amount       bigint not null default 0
);

create index if not exists budgets_month_idx on public.budgets (month);

create table if not exists public.goals (
  id              text primary key,
  name            text not null,
  "targetAmount"  bigint not null default 0,
  "currentAmount" bigint not null default 0,
  "targetDate"    text,
  icon            text,
  color           text
);

create table if not exists public.accounts (
  id               text primary key,
  name             text not null,
  type             text not null default 'bank',
  owner            text default 'shared',
  "bankName"       text,
  "openingBalance" bigint not null default 0
);

create table if not exists public.recurring (
  id              text primary key,
  name            text not null,
  type            text not null default 'expense',
  amount          bigint not null default 0,
  "categoryId"    text,
  "userId"        text,
  "sharedType"    text,
  "paymentMethod" text,
  "accountId"     text,
  "dayOfMonth"    integer not null default 1,
  memo            text,
  active          boolean not null default true,
  "startMonth"    text,
  "endMonth"      text
);

create table if not exists public.settlements (
  id            text primary key,
  month         text not null,
  mode          text,
  amount        bigint not null default 0,
  "fromUserId"  text,
  "toUserId"    text,
  "sharedTotal" bigint not null default 0,
  "husbandPaid" bigint not null default 0,
  "wifePaid"    bigint not null default 0,
  "settledAt"   timestamptz default now()
);

create unique index if not exists settlements_month_idx on public.settlements (month);

-- 부부 공유 설정 (정산 기준 등). 항목이 늘어나도 스키마를 바꾸지 않도록 jsonb 로 둡니다.
create table if not exists public.app_settings (
  id   text primary key,
  data jsonb not null default '{}'::jsonb
);

-- 카드 청구 주기 컬럼 (기존 accounts 테이블에도 안전하게 추가됩니다)
alter table public.accounts add column if not exists "statementDay"       integer default 31;
alter table public.accounts add column if not exists "paymentDay"         integer default 25;
